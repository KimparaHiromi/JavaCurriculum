package curriculum.k;

/**********************************************************************************
* [概要] 社員の給与レポートを出力する「クラス」
* [詳細] 
* ① 「Payable」インターフェースを持つオブジェクトを受け取る
* ② そのオブジェクトに対して名前と給与を問い合せ、画面に出力する
**********************************************************************************/

public class SalaryReporter {

    /*-------------------------------------------------------------------------
    [概要] レポート出力処理
    [引数] Payable p : Payable : インターフェースを実装した任意のクラスのインスタンス（ 「p」とする ）
    -------------------------------------------------------------------------*/
    public void report(Payable p) {
    	
        String name = p.getName();
        long salary = p.calculate();
        
        System.out.println(name + " の給料は " + salary + " 円");
    }
}



